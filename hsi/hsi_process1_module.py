#PCA is used to find Principal Components of Ice Core
def PrincipalComponents(img):
    #data_2d = np.array([features_2d.flatten() for features_2d in data])
    data = img.reshape(-1,224)
    #print("Shape: ", data.shape)
    principal=PCA(n_components=3)
    principal.fit(data)

    for i, component in enumerate(principal.components_, start=1):
        plt.figure()
        plt.plot(component)
        plt.title(f"PCA  {i}")
        plt.xlabel("Original Features (Spectral Bands)")
        plt.ylabel("Weight")
        plt.grid(True)
        plt.show()

    return 0

